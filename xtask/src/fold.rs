//! `cargo xtask fold`: the table search folds letters with (`crates/model/src/search/fold_table.rs`),
//! so `resume` finds "Résumé" and `strasse` "Straße".
//!
//! Each lower-case letter of Latin, Greek and the fullwidth forms is taken apart (NFKD, from
//! icu_normalizer here, so the model and the browser build carry no normalizer), its accents
//! (U+0300–U+036F) dropped and the rest lower-cased; the letters that change are the table, with
//! a few by hand that Unicode doesn't take apart (ß, æ, ø, œ, ł, đ, ð, þ, ı, ё, ς). Cyrillic
//! otherwise stays as it is (й isn't и in Russian), and so does every other script.
//! `fold --check` (part of `cargo xtask ci`) fails when the table written differs from the one
//! this makes, or when it would no longer fit in a file.

use std::collections::BTreeMap;
use std::path::Path;

use icu_normalizer::DecomposingNormalizerBorrowed;

/// Where the table goes, from the workspace root.
const TABLE: &str = "crates/model/src/search/fold_table.rs";
/// Code points looked at: Latin-1 and Latin Extended A and B, Latin Extended Additional, Greek
/// and Coptic, Greek Extended, the fullwidth ASCII forms.
const RANGES: &[(u32, u32)] = &[(0xC0, 0x24F), (0x1E00, 0x1EFF), (0x370, 0x3FF), (0x1F00, 0x1FFF), (0xFF01, 0xFF5E)];
/// Letters Unicode doesn't take apart, read as a person typing without them would.
const BY_HAND: &[(char, &str)] =
    &[('ß', "ss"), ('æ', "ae"), ('ø', "o"), ('œ', "oe"), ('ł', "l"), ('đ', "d"), ('ð', "d"), ('þ', "th"), ('ı', "i"), ('ё', "е"), ('ς', "σ")];
/// Letters per line of the table.
const PER_LINE: usize = 8;

/// An accent, as fold_word drops it.
fn is_mark(c: char) -> bool {
    ('\u{300}'..='\u{36F}').contains(&c)
}

/// The table: each lower-case letter that folds, and what it folds to.
fn rows() -> BTreeMap<char, String> {
    let nfkd = DecomposingNormalizerBorrowed::new_nfkd();
    let hand = |c: char| BY_HAND.iter().find(|(k, _)| *k == c).map_or_else(|| c.to_string(), |(_, s)| s.to_string());
    let mut out: BTreeMap<char, String> = BTreeMap::new();
    for &(lo, hi) in RANGES {
        for c in (lo..=hi).filter_map(char::from_u32) {
            // The letter as fold_word sees it: lower-cased first.
            let mut lower = c.to_lowercase();
            let (Some(l), None) = (lower.next(), lower.next()) else { continue };
            let folded: String = nfkd.normalize(&l.to_string()).chars().filter(|c| !is_mark(*c)).flat_map(char::to_lowercase).map(hand).collect();
            // A spacing accent alone comes apart into a space: not a letter to fold.
            if folded.is_empty() || folded.chars().any(char::is_whitespace) || folded == l.to_string() {
                continue;
            }
            out.insert(l, folded);
        }
    }
    for (c, s) in BY_HAND {
        out.insert(*c, s.to_string());
    }
    out
}

/// The table's source.
fn source() -> Result<String, String> {
    let rows = rows();
    // Folding twice must change nothing: what a letter folds to holds no letter that folds.
    for (c, s) in &rows {
        if s.chars().any(|t| rows.contains_key(&t) || t.to_lowercase().ne(std::iter::once(t)) || is_mark(t)) {
            return Err(format!("{c:?} folds to {s:?}, which folds again"));
        }
    }
    let mut out = String::from(
        "//! Generated by `cargo xtask fold` (xtask/src/fold.rs) from Unicode's decompositions: don't edit\n\
         //! it by hand. Each lower-case letter that search reads as another, sorted.\n\n\
         /// Lower-case letter → what search reads it as (sorted by letter, for a binary search).\n\
         #[rustfmt::skip]\n\
         pub(super) const FOLD: &[(char, &str)] = &[\n",
    );
    let rows: Vec<(&char, &String)> = rows.iter().collect();
    for line in rows.chunks(PER_LINE) {
        let cells: Vec<String> = line.iter().map(|(c, s)| format!("({c:?}, {s:?})")).collect();
        out.push_str("    ");
        out.push_str(&cells.join(", "));
        out.push_str(",\n");
    }
    out.push_str("];\n");
    if out.lines().count() > crate::sizes::MAX_LINES {
        return Err(format!("the fold table would be {} lines, past {}", out.lines().count(), crate::sizes::MAX_LINES));
    }
    Ok(out)
}

pub fn run(root: &Path, args: &[&str]) -> Result<(), String> {
    let want = source()?;
    let path = root.join(TABLE);
    if args.contains(&"--check") {
        let have = std::fs::read_to_string(&path).map_err(|e| format!("{TABLE}: {e}"))?.replace("\r\n", "\n");
        if have != want {
            return Err(format!("{TABLE} isn't what `cargo xtask fold` makes: run it and commit the table"));
        }
        println!("fold: {TABLE} is up to date ({} lines)", want.lines().count());
        return Ok(());
    }
    std::fs::write(&path, want.as_bytes()).map_err(|e| format!("{TABLE}: {e}"))?;
    println!("fold: wrote {TABLE} ({} lines)", want.lines().count());
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;

    /// Accents go, the letters by hand fold, and what isn't Latin or Greek stays.
    #[test]
    fn the_table_folds_accents_and_keeps_other_scripts() {
        let rows = rows();
        let get = |c: char| rows.get(&c).map(String::as_str);
        assert_eq!(get('é'), Some("e"));
        assert_eq!(get('ǣ'), Some("ae"), "an accent on a letter folded by hand");
        assert_eq!(get('ά'), Some("α"));
        assert_eq!(get('ａ'), Some("a"));
        assert_eq!(get('ß'), Some("ss"));
        assert_eq!(get('ё'), Some("е"));
        assert_eq!((get('й'), get('e'), get('É')), (None, None, None), "й stays, plain letters and capitals aren't keys");
        assert!(source().is_ok_and(|s| s.lines().count() < 1000));
    }
}
