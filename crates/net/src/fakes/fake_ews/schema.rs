/// The first field an operation names that the schema doesn't know, or that this server
/// refuses (`refused`, a stricter server's): `None` when it knows them all.
pub(super) fn unknown_field(op: &El, refused: &[String]) -> Option<String> {
    let mut fields = Vec::new();
    op.all("FieldURI", &mut fields);
    fields.iter().filter_map(|f| f.attr("FieldURI")).find(|u| !KNOWN.contains(u) || refused.iter().any(|r| r == u)).map(str::to_string)
}
